import { positionAt } from './odometer';

describe('одометр MoneyFlow', () => {
  it('в покое каждая лента стоит ровно на своей цифре', () => {
    // 1 877,21 → 187721: младший разряд справа
    const u = 187721;
    expect([5, 4, 3, 2, 1, 0].map((p) => positionAt(u, p))).toEqual([1, 8, 7, 7, 2, 1]);
  });

  it('старший разряд в покое не «подглядывает», даже если младшие на девятках', () => {
    // Ошибка, которая легко прячется: если двигать разряд по доле младших,
    // то при «…98» десятки уже были бы на полпути к следующей цифре.
    expect(positionAt(298, 1)).toBe(9);
    expect(positionAt(298, 2)).toBe(2);
  });

  it('при переносе 9 → 0 старший разряд едет вместе с младшим, на ту же долю', () => {
    expect(positionAt(29.5, 0)).toBeCloseTo(9.5, 6);
    expect(positionAt(29.5, 1)).toBeCloseTo(2.5, 6);
    // и дальше по цепочке: 299,5 — катятся сразу два разряда
    expect(positionAt(299.5, 1)).toBeCloseTo(9.5, 6);
    expect(positionAt(299.5, 2)).toBeCloseTo(2.5, 6);
  });

  it('вне переноса старший разряд стоит, пока младший крутится', () => {
    expect(positionAt(24.5, 1)).toBe(2);
    expect(positionAt(24.5, 0)).toBeCloseTo(4.5, 6);
  });
});
