/**
 * Шейдер hero-поля: «живое состояние капитала».
 *
 * Рисует не объект, а плотность света. Композиция строится из нескольких
 * крупных мягких масс, которые прогоняются через доменный варп — именно варп
 * даёт S-образные складки и ощущение течения. Без него слои читаются как
 * круги, и получается лава-лампа (прямо запрещено в спеке).
 *
 * Возвращаем ПРЕМУЛЬТИПЛИЦИРОВАННЫЙ цвет с альфой: поле лежит поверх обычного
 * градиента экрана, и края должны честно растворяться в нём, а не закрашивать
 * его своим «почти белым».
 *
 * Юниформы:
 *   u_res       — размер канваса в пикселях
 *   u_time      — секунды (своя, останавливаемая; см. HeroField)
 *   u_intensity — 0..1 общая живость: амплитуда варпа, плотность, альфа
 *   u_warmth    — 0..1 сдвиг палитры из холодного голубого в мятно-зелёный
 */
export const HERO_SHADER = `
uniform float2 u_res;
uniform float  u_time;
uniform float  u_intensity;
uniform float  u_warmth;

// Мягкая масса без границы. Радиусы разные по осям — массы вытянутые,
// иначе они опознаются как «кружки-активы», чего спека прямо не хочет.
float mass(float2 p, float2 c, float2 r) {
  float2 d = (p - c) / r;
  return exp(-dot(d, d));
}

// ПОТОК: вытянутая лента вдоль изогнутой линии, в СВОЁМ повёрнутом базисе.
// Сумма круглых масс давала одно облако; «несколько течений» читается только
// когда ленты идут под разными углами и пересекаются.
float stream(float2 w, float t, float ang, float y0, float amp, float freq,
             float phase, float speed, float thick, float len) {
  float ca = cos(ang), sa = sin(ang);
  float rx =  w.x * ca + w.y * sa;
  float ry = -w.x * sa + w.y * ca;
  float dy = (ry - (y0 + amp * sin(rx * freq + t * speed + phase))) / thick;
  float dx = rx / len;
  return exp(-dy * dy) * exp(-dx * dx);
}

half4 main(float2 fragCoord) {
  float2 uv = fragCoord / u_res;
  // Координаты с поправкой на пропорции: 1.0 = высота поля. Центр по вертикали
  // стоит ровно на строке суммы, а не в геометрической середине.
  float2 p = (uv - float2(0.5, 0.575)) * float2(u_res.x / u_res.y, 1.0);
  float t = u_time;
  float k = u_intensity;

  // Доменный варп в два прохода: первый гнёт крупно, второй добавляет
  // мелкую складку. Амплитуда первого намеренно небольшая — он сдвигает поле
  // целиком, и на большой амплитуде масса уползает из-под суммы.
  float2 q = p;
  q.x += (0.045 + 0.030 * k) * sin(p.y * 3.1 + t * 0.27);
  q.y += (0.055 + 0.030 * k) * sin(p.x * 2.3 - t * 0.21);
  float2 w = q;
  w.x = q.x + 0.100 * sin(q.y * 6.6 - t * 0.16);
  w.y = q.y + 0.080 * sin(q.x * 5.2 + t * 0.19);

  float s1 = 0.62 * stream(w, t, -0.24, -0.06, 0.090, 2.6, 0.0, 0.23, 0.125, 1.05);
  float s2 = 0.52 * stream(w, t,  0.16,  0.13, 0.075, 3.4, 1.9, -0.19, 0.100, 0.95);
  float s3 = 0.44 * stream(w, t, -0.38, -0.24, 0.100, 2.1, 3.3, 0.15, 0.090, 0.85);
  float s4 = 0.36 * stream(w, t,  0.31,  0.24, 0.065, 4.1, 5.0, -0.26, 0.080, 0.88);
  float d = s1 + s2 + s3 + s4;

  // Общая масса под суммой: потоки дают полосы, а спека просит ещё и
  // концентрацию плотности вокруг цифры.
  d += 0.38 * mass(w, float2(0.02 * sin(t * 0.13), -0.02),                float2(0.60, 0.30));
  d += 0.20 * mass(w, float2(-0.28 + 0.06 * sin(t * 0.17), 0.08),         float2(0.46, 0.24));
  d += 0.18 * mass(w, float2(0.28 + 0.05 * sin(t * 0.15 + 1.7), -0.10),   float2(0.44, 0.22));

  float ripple = 0.5 + 0.5 * sin(w.y * 7.0 + w.x * 3.0 + t * 0.33);
  d *= 0.78 + 0.22 * ripple;

  // Широкая дымка на весь верх — без неё углы пустые и поле выглядит линзой,
  // приклеенной к центру, а не состоянием всей верхней части экрана.
  float veil = (uv.y - 0.32) / 0.52;
  d += 0.30 * exp(-veil * veil) * (0.55 + 0.45 * ripple);
  d *= 0.55 + 0.45 * k;

  // 60-70% массы держим в центральной зоне: к краям поле беднеет.
  float2 m = p * float2(0.85, 1.25);
  d *= 0.30 + 0.70 * exp(-dot(m, m) * 1.05);

  // Снизу растворяемся до контента; сверху не в ноль, а до 0.45 — цвет должен
  // доходить до самого верха экрана, иначе hero читается как отдельная плашка.
  d *= smoothstep(1.02, 0.58, uv.y) * (0.45 + 0.55 * smoothstep(-0.30, 0.30, uv.y));
  d = clamp(d, 0.0, 1.4);

  // У каждого потока СВОЙ оттенок, и цвет точки — их взвешенная смесь. Именно
  // это, а не разница в плотности, заставляет читать несколько течений: вдоль
  // ленты оттенок свой, на пересечениях они смешиваются. Палитра нарочно
  // светлая: поверх поля лежит тёмный текст, и на плотной бирюзе он тонет.
  half3 cAqua = half3(0.616, 0.906, 0.949);
  half3 cMint = half3(0.549, 0.910, 0.784);
  half3 cTeal = half3(0.427, 0.835, 0.847);
  half3 cSky  = half3(0.694, 0.878, 0.976);
  half3 base  = half3(0.780, 0.929, 0.961);
  half3 green = half3(0.494, 0.898, 0.729);

  float wsum = s1 + s2 + s3 + s4 + 0.0001;
  half3 colS = (half(s1) * cTeal + half(s2) * cMint + half(s3) * cSky + half(s4) * cAqua) / half(wsum);
  colS = mix(colS, green, half(0.42 * u_warmth));
  half3 col = mix(base, colS, half(clamp(wsum * 2.2, 0.0, 1.0)));

  // Разгон альфы без насыщения: если оборвать его на 0.9, ядро становится
  // плоской заливкой и все складки внутри пропадают.
  float a = (0.26 + 0.60 * k) * smoothstep(0.02, 1.30, d);
  // Дизер: на таких больших плавных заливках 8-битный градиент иначе полосит.
  a += (fract(sin(dot(fragCoord, float2(12.9898, 78.233))) * 43758.5453) - 0.5) * 0.006;
  a = clamp(a, 0.0, 0.82);

  return half4(col * half(a), half(a));
}
`;
