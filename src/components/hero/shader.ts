/**
 * Шейдер hero-поля: «живое состояние капитала».
 *
 * Рисует не объект, а плотность света. Композиция строится из нескольких
 * крупных мягких масс, которые прогоняются через доменный варп — именно варп
 * даёт S-образные складки и ощущение течения. Без него слои читаются как
 * круги, и получается лава-лампа (прямо запрещено в спеке).
 *
 * Возвращаем ПРЕМУЛЬТИПЛИЦИРОВАННЫЙ цвет с альфой: поле лежит поверх обычного
 * градиента экрана, и края должны честно растворяться в нём, а не закрашивать
 * его своим «почти белым».
 *
 * Юниформы:
 *   u_res       — размер канваса в пикселях
 *   u_time      — секунды (своя, останавливаемая; см. HeroField)
 *   u_intensity — 0..1 общая живость: амплитуда варпа, плотность, альфа
 *   u_warmth    — 0..1 сдвиг палитры из холодного голубого в мятно-зелёный
 */
export const HERO_SHADER = `
uniform float2 u_res;
uniform float  u_time;
uniform float  u_intensity;
uniform float  u_warmth;

// Мягкая масса без границы. Радиусы разные по осям — массы вытянутые,
// иначе они опознаются как «кружки-активы», чего спека прямо не хочет.
float mass(float2 p, float2 c, float2 r) {
  float2 d = (p - c) / r;
  return exp(-dot(d, d));
}

half4 main(float2 fragCoord) {
  float2 uv = fragCoord / u_res;
  // Координаты с поправкой на пропорции: 1.0 = высота поля.
  float2 p = (uv - float2(0.5, 0.62)) * float2(u_res.x / u_res.y, 1.0);
  float t = u_time;
  float k = u_intensity;

  // Доменный варп в два прохода: первый гнёт крупно, второй добавляет
  // мелкую складку. Разные частоты и скорости — чтобы период не считывался.
  float2 q = p;
  q.x += (0.10 + 0.05 * k) * sin(p.y * 3.1 + t * 0.27);
  q.y += (0.08 + 0.04 * k) * sin(p.x * 2.3 - t * 0.21);
  float2 w = q;
  w.x += 0.055 * sin(q.y * 5.4 - t * 0.16);
  w.y += 0.045 * sin(q.x * 4.1 + t * 0.19);

  float d = 0.0;
  d += 1.00 * mass(w, float2( 0.02 * sin(t * 0.13),        -0.04 + 0.03 * sin(t * 0.11)), float2(0.52, 0.32));
  d += 0.72 * mass(w, float2(-0.30 + 0.06 * sin(t * 0.17),  0.10),                        float2(0.40, 0.25));
  d += 0.68 * mass(w, float2( 0.29 + 0.05 * sin(t * 0.15 + 1.7), -0.13),                  float2(0.38, 0.23));
  d += 0.42 * mass(w, float2( 0.05,  0.22 + 0.04 * sin(t * 0.09)),                        float2(0.58, 0.19));
  d += 0.32 * mass(w, float2(-0.10 + 0.08 * sin(t * 0.07 + 2.3), -0.26),                  float2(0.48, 0.17));

  // Внутренняя неоднородность — те самые «складки» в толще массы.
  float ripple = 0.5 + 0.5 * sin(w.y * 7.0 + w.x * 3.0 + t * 0.33);
  d *= 0.86 + 0.14 * ripple;
  d *= 0.55 + 0.45 * k;

  // 60-70% массы держим в центральной зоне: к краям поле резко беднеет.
  float2 m = p * float2(0.85, 1.25);
  d *= 0.32 + 0.68 * exp(-dot(m, m) * 1.15);

  // Сверху уходим под шапку почти нулём, снизу растворяемся до контента.
  d *= smoothstep(1.06, 0.62, uv.y) * smoothstep(-0.20, 0.26, uv.y);
  d = clamp(d, 0.0, 1.4);

  half3 cool = half3(0.694, 0.878, 0.933); // холодный голубой
  half3 mid  = half3(0.514, 0.831, 0.859); // бирюза
  half3 warm = half3(0.443, 0.827, 0.690); // мятно-зелёный
  half3 deep = half3(0.259, 0.643, 0.639); // глубокий teal (только в ядре)

  half3 col = mix(cool, mid, half(smoothstep(0.15, 0.75, d)));
  col = mix(col, warm, half(u_warmth * smoothstep(0.35, 1.00, d)));
  col = mix(col, deep, half(smoothstep(0.85, 1.35, d) * (0.30 + 0.45 * k)));

  float a = (0.16 + 0.50 * k) * smoothstep(0.02, 0.90, d);
  // Дизер: на таких больших плавных заливках 8-битный градиент иначе полосит.
  a += (fract(sin(dot(fragCoord, float2(12.9898, 78.233))) * 43758.5453) - 0.5) * 0.006;
  a = clamp(a, 0.0, 0.86);

  return half4(col * half(a), half(a));
}
`;
