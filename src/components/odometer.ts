/**
 * Чистая математика одометра — отдельно от компонента, чтобы её можно было
 * проверить тестом без нативной части Reanimated (как heroState отделён от
 * hero-поля). Функция — worklet: её же зовёт UI-поток в MoneyFlow.
 */

/**
 * Положение ленты разряда `place` (0 — младший) при значении `u`, от 0 до 10.
 *
 * Младший разряд крутится непрерывно. Старший трогается только тогда, когда
 * разряд под ним переходит с 9 на 0, и ровно на ту же долю — так устроен
 * настоящий одометр. В покое `u` целое, переносов нет, и каждая лента стоит
 * ровно на своей цифре.
 */
export function positionAt(u: number, place: number): number {
  'worklet';
  let pos = ((u % 10) + 10) % 10;
  let p = 1;
  for (let k = 1; k <= place; k++) {
    p *= 10;
    const digit = Math.floor(u / p) % 10;
    const carry = pos > 9 ? pos - 9 : 0;
    pos = digit + carry;
  }
  return pos;
}
