import { makeMutable } from 'react-native-reanimated';

/**
 * Непрозрачность маски статус-бара (см. StatusBarMask в `app/_layout.tsx`).
 *
 * Маска нужна, когда контент уезжает под системные иконки — но в НЕпрокрученном
 * состоянии главной она отрезала верх живого hero-поля ровной серой полосой.
 * Поэтому непрозрачность стала общей величиной: экран, которому есть что
 * показать под строкой, опускает её у себя и обязан вернуть 1 на расфокусе —
 * иначе следующий экран останется без маски и получит кашу под иконками.
 *
 * Значение по умолчанию 1: экран, который про эту механику не знает, ведёт
 * себя ровно как раньше.
 */
export const statusBarVeil = makeMutable(1);

/** Порог, за которым маска уже полностью закрыта (px прокрутки). */
export const VEIL_SCROLL = 56;

export function veilForOffset(y: number): number {
  'worklet';
  return Math.min(1, Math.max(0, y / VEIL_SCROLL));
}
