/** «42 площадки» — склонение для подписей «памятка по N площадкам». */
export function pluralPlatforms(n: number): string {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 'площадка';
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'площадки';
  return 'площадок';
}

export function timingsBy(when: OpenWhen): BankTiming[] {
  return BANK_TIMING.filter((t) => t.openWhen === when);
}

function normalize(s: string): string {
  return s.toLowerCase().replace(/[^a-zа-яё0-9+]/gi, '');
}

/**
 * Памятка для площадки пользователя. Сначала по id из реестра (надёжно), потом
 * по имени — вхождением в обе стороны, потому что в памятке банк может быть
 * подписан вместе с продуктом («Реалист «Премиальный старт»»), а у пользователя
 * площадка названа просто банком — и наоборот.
 *
 * Из нескольких совпадений берём САМОЕ ДЛИННОЕ, а не первое: «Реалист» и
 * «Реалист «Премиальный старт»» — разные группы, и площадка, названная вместе с
 * продуктом, по первому совпадению улетела бы в группу голого «Реалиста».
 *
 * Короткие имена в префиксный поиск не пускаем: «Т» совпало бы с «ТКБ».
 */
export function timingForOrg(org: { name: string; logo?: string }): BankTiming | undefined {
  if (org.logo) {
    const byId = BANK_TIMING.find((t) => t.bankId === org.logo);
    if (byId) return byId;
  }
  const n = normalize(org.name);
  if (!n) return undefined;

  const exact = BANK_TIMING.find((t) => normalize(t.name) === n);
  if (exact) return exact;
  if (n.length < 3) return undefined;

  let best: BankTiming | undefined;
  let bestLen = 0;
  for (const t of BANK_TIMING) {
    const m = normalize(t.name);
    if (m.length < 3) continue;
    if (!m.startsWith(n) && !n.startsWith(m)) continue;
    if (m.length > bestLen) {
      best = t;
      bestLen = m.length;
    }
  }
  return best;
}
