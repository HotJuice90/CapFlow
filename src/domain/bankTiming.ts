/**
 * Памятка «когда открывать и закрывать накопительный счёт».
 *
 * Под тремя списками источника лежит ОДНА механика — к чему банк привязывает
 * расчётный период:
 *  - к календарному месяцу, НЕ считая день открытия → выгодно открыть в
 *    последний день: первый полный месяц начнётся со следующего ('lastDay');
 *  - к календарному месяцу, считая день открытия → открывшись 30-го, сжигаешь
 *    первый период за один день, поэтому ждём 1-го ('firstDay');
 *  - к дате открытия (N расчётных периодов или N дней) → день любой ('anyDay').
 *
 * Поэтому храним именно это, а не три плоских списка: по признаку можно будет
 * отвечать на вопросы, которых в памятке нет.
 *
 * ВАЖНО: это сторонняя памятка на конкретную дату (`TIMING_AS_OF`), а не
 * условия из договора. Банки меняют правила, а список зашит в приложение и
 * обновляется только с релизом — дату показываем на экране явно.
 */

import { findBankByName } from './banks';

export type OpenWhen =
  /** В последний день месяца. */
  | 'lastDay'
  /** С 1 числа нового месяца. */
  | 'firstDay'
  /** В любой день — период считается от даты открытия. */
  | 'anyDay';

export interface BankTiming {
  /** Название площадки — как в источнике. */
  name: string;
  /** id из BANKS, если лого у нас есть. Заполняется автоматически по имени. */
  bankId?: string;
  openWhen: OpenWhen;
  /** Уточнение к открытию: длина расчётного периода, оговорки по продуктам. */
  openNote?: string;
  /** Когда платят проценты — он же день, когда деньги можно выводить. */
  payout?: string;
  /** Чем закрытие отличается от общего правила. */
  closeNote?: string;
  /** Всё остальное, что важно знать по счёту. */
  note?: string;
}

