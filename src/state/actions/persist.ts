import type { AppData } from '@/storage/types';

/**
 * Единственный способ записать данные. Принимает ФУНКЦИЮ от актуального
 * состояния, а не готовый объект — и это не стилистика, а лечение конкретного
 * класса багов: экшены собираются вокруг снимка `data` из замыкания, поэтому
 * два вызова подряд из одного обработчика (закрыть актив + вернуть деньги в
 * свободные) считали бы `next` от ОДНОГО И ТОГО ЖЕ снимка, и второй persist
 * затирал бы первый. Симптом обманчивый: видимый результат даёт последний
 * вызов, а первый пропадает молча (деньги пришли в кошелёк, а актив остался
 * открытым). Для чтения `data` из замыкания по-прежнему годится — врут только
 * записи.
 */
export type Persist = (update: (prev: AppData) => AppData) => Promise<void>;
